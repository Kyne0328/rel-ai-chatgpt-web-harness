  ChevronLeft,
  ChevronRight,
  CircleCheck,
  CircleHelp,
  Code2,
  Ellipsis,
  ExternalLink,
  Folder,
  FolderKanban,
  Globe2,
  Info,
  LayoutDashboard,
  Link2,
  ListTodo,
  Maximize2,
  Minimize2,
  Minus,
  Monitor,
  Moon,
  PanelLeftClose,
