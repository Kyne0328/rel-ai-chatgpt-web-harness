function tokenValue(source, name) {
  const escaped = name.replace(/[.*+?^${}()|[\]\\]/g, String.raw`\$&`);
  const match = source.match(new RegExp(String.raw`${escaped}\s*:\s*([^;]+);`));
  assert.ok(match, `Missing token ${name}`);
  return match[1].trim().replace(/\s+/g, ' ');
}

