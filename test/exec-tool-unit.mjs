function removeTempAfterHandlesClose() {
  const options = { recursive: true, force: true, maxRetries: process.platform === 'win32' ? 20 : 2, retryDelay: 100 };
  try {
    fs.rmSync(temp, options);
    return;
  } catch (error) {
    if (process.platform !== 'win32' || error?.code !== 'EPERM') throw error;
  }

  const cleanupScript = `
    const fs = require('node:fs');
    const target = process.argv[1];
    let attempts = 0;
    const remove = () => {
      try {
        fs.rmSync(target, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 });
        process.exit(0);
      } catch {
        attempts += 1;
        if (attempts >= 50) process.exit(0);
        setTimeout(remove, 100);
      }
    };
    setTimeout(remove, 100);
  `;
  const cleanup = spawn(process.execPath, ['-e', cleanupScript, temp], {
    detached: true,
    stdio: 'ignore',
    windowsHide: true
  });
  cleanup.unref();
}
